"""Stripe webhook signature verification using the official Stripe SDK helper.

Per Stripe documentation (https://docs.stripe.com/webhooks/signature):
Stripe-Signature headers carry timestamp t and HMAC-SHA256 signatures v1.
stripe.WebhookSignature.generate_signature_header is the official library helper
for generating test headers. Tests verify that the app:
1. Accepts valid signatures generated by the SDK.
2. Rejects payloads tampered after signing.
3. Rejects timestamps outside tolerance.
4. Accepts headers with multiple v1 signatures when at least one matches
   (used during webhook secret rolling).
"""

import json
import secrets
import time

import stripe
from pydantic import SecretStr

from app.core.config import settings

WEBHOOK_URL = "/api/v1/orders/webhooks/stripe"


def test_app_accepts_webhook_signature_generated_by_official_sdk(client, monkeypatch):
    """The application accepts a webhook signed with the official Stripe SDK helper."""
    test_secret = "test-secret-" + secrets.token_hex(8)
    monkeypatch.setattr(settings, "STRIPE_WEBHOOK_SECRET", SecretStr(test_secret))

    payload = json.dumps({
        "id": "evt_test_sdk_valid",
        "object": "event",
        "type": "payment_intent.succeeded",
        "data": {"object": {"id": "pi_test_sdk_valid", "amount": 1000}},
    })

    header = stripe.WebhookSignature.generate_signature_header(
        payload, test_secret, timestamp=int(time.time())
    )

    response = client.post(
        WEBHOOK_URL,
        content=payload.encode("utf-8"),
        headers={"Stripe-Signature": header, "Content-Type": "application/json"},
    )
    assert response.status_code == 200
    assert response.json() == {"status": "received"}


def test_app_rejects_tampered_payload_with_sdk_signature(client, monkeypatch):
    """The application rejects a payload modified after signing."""
    test_secret = "test-secret-" + secrets.token_hex(8)
    monkeypatch.setattr(settings, "STRIPE_WEBHOOK_SECRET", SecretStr(test_secret))

    payload = json.dumps({
        "id": "evt_test_sdk_tampered",
        "object": "event",
        "type": "payment_intent.succeeded",
        "data": {"object": {"id": "pi_test_sdk_tampered", "amount": 1000}},
    })

    header = stripe.WebhookSignature.generate_signature_header(
        payload, test_secret, timestamp=int(time.time())
    )

    tampered_payload = payload.replace("1000", "2000")
    response = client.post(
        WEBHOOK_URL,
        content=tampered_payload.encode("utf-8"),
        headers={"Stripe-Signature": header, "Content-Type": "application/json"},
    )
    assert response.status_code == 400
    assert "Invalid webhook signature" in response.json()["detail"]


def test_app_rejects_timestamp_outside_tolerance_with_sdk_signature(client, monkeypatch):
    """The application rejects a timestamp older than the tolerance window."""
    test_secret = "test-secret-" + secrets.token_hex(8)
    monkeypatch.setattr(settings, "STRIPE_WEBHOOK_SECRET", SecretStr(test_secret))
    tolerance = settings.STRIPE_WEBHOOK_TOLERANCE_SECONDS

    payload = json.dumps({
        "id": "evt_test_sdk_expired",
        "object": "event",
        "type": "payment_intent.succeeded",
        "data": {"object": {"id": "pi_test_sdk_expired", "amount": 1000}},
    })

    old_timestamp = int(time.time()) - (tolerance + 60)
    header = stripe.WebhookSignature.generate_signature_header(
        payload, test_secret, timestamp=old_timestamp
    )

    response = client.post(
        WEBHOOK_URL,
        content=payload.encode("utf-8"),
        headers={"Stripe-Signature": header, "Content-Type": "application/json"},
    )
    assert response.status_code == 400
    assert "Invalid webhook signature" in response.json()["detail"]


def test_app_accepts_multiple_v1_signatures_where_one_is_valid(client, monkeypatch):
    """During secret rotation, Stripe sends multiple v1 signatures; any valid match is accepted."""
    test_secret = "test-secret-" + secrets.token_hex(8)
    other_secret = "test-secret-" + secrets.token_hex(8)
    monkeypatch.setattr(settings, "STRIPE_WEBHOOK_SECRET", SecretStr(test_secret))

    payload = json.dumps({
        "id": "evt_test_sdk_multisig",
        "object": "event",
        "type": "payment_intent.succeeded",
        "data": {"object": {"id": "pi_test_sdk_multisig", "amount": 1000}},
    })

    now = int(time.time())
    valid_sig = stripe.WebhookSignature._compute_signature(f"{now}.{payload}", test_secret)
    invalid_sig = stripe.WebhookSignature._compute_signature(f"{now}.{payload}", other_secret)

    # Valid signature preceded by another secret's signature
    header = f"t={now},v1={invalid_sig},v1={valid_sig}"

    response = client.post(
        WEBHOOK_URL,
        content=payload.encode("utf-8"),
        headers={"Stripe-Signature": header, "Content-Type": "application/json"},
    )
    assert response.status_code == 200
    assert response.json() == {"status": "received"}
