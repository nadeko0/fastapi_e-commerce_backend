"""
Property-based checks of the order arithmetic and of stock, driven through
the real API (cart -> checkout -> cancel / pay / expiry) on generated input.

- Money: an order's total is exactly the sum of price_at_time x quantity in
  Decimal, each line priced at the variant's price_override when it has one
  and at the product's price otherwise, and the amount charged in cents is
  that total x 100 with nothing lost to float rounding.
- Stock: whatever sequence of checkouts, cancellations (customer, admin),
  payments and expiry runs, a product's stock is its starting stock minus
  what its live (not cancelled) orders hold. It never goes below zero (no
  oversell) and nothing is returned twice (no double restock).

Hypothesis runs many examples inside one test function, so the per-test
fixtures (database, fake Redis) are shared by the examples of a test: each
example makes its own products and buyers and checks only those.
"""
