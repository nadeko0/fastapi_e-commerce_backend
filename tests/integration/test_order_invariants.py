def _buyer(db, role="client"):
    """A user who can check out (verified, complete profile, one address).
    Returns (auth headers, address id)."""
    user = User(
        email=f"u-{uuid.uuid4().hex[:12]}@example.com",
        hashed_password=get_password_hash("Str0ngPass1"),
        full_name="Prop Buyer",
        phone="+15551234567",
        role=role,
        is_active=True,
        is_email_verified=True,
        gdpr_consent=True,
        privacy_policy_accepted=True,
    )
    db.add(user)
    db.commit()
    address = Address(user_id=user.id, street=f"{uuid.uuid4().hex[:6]} St", city="City",
                      state="ST", postal_code="10001", country="US")
    db.add(address)
    db.commit()
    return {"Authorization": f"Bearer {create_access_token(user.id)}"}, address.id


def _product(db, price, stock):
    category = Category(name=f"c-{uuid.uuid4().hex[:8]}", path=[], level=0)
    db.add(category)
    db.commit()
    product = Product(name="Prop item", description="Generated by a property test",
                      price=price, stock_quantity=stock, category_id=category.id,
                      images=["https://x.test/a.png"])
    db.add(product)
    db.commit()
    return product


def _variant(db, product, price_override, stock):
    variant = ProductVariant(product_id=product.id, sku=f"SKU-{uuid.uuid4().hex[:10]}",
                             attributes={"size": "M"}, price_override=price_override,
                             stock_quantity=stock)
    db.add(variant)
    db.commit()
    return variant


def _checkout(client, headers, address_id):
    return client.post(ORDERS, params={"shipping_address_id": address_id},
                       headers={**headers, "Idempotency-Key": uuid.uuid4().hex})


# -- Money -------------------------------------------------------------------

@given(amount=prices, quantity=st.integers(min_value=1, max_value=1000))
def test_cents_conversion_is_exact_and_round_trips(amount, quantity):
    cents = _decimal_to_cents(amount)
    assert isinstance(cents, int)
    assert Decimal(cents) == amount * 100
    assert _cents_to_decimal(cents) == amount
    # Charging a line in cents equals converting the line total.
    assert _decimal_to_cents(amount * quantity) == cents * quantity


line = st.fixed_dictionaries({
    "price": prices,
    "quantity": st.integers(min_value=1, max_value=5),
    # None: a plain product line. Otherwise a variant line, whose override
    # may itself be None (the variant inherits the product's price).
    "variant": st.none() | st.fixed_dictionaries({"override": st.none() | prices}),
})


@hyp_settings(max_examples=25, **_HYPOTHESIS)
@given(lines=st.lists(line, min_size=1, max_size=4))
def test_order_total_is_the_exact_decimal_sum_of_its_lines(client, db_session, lines):
    headers, address_id = _buyer(db_session)
    expected_total = Decimal("0.00")
    expected_prices = {}
    stocks = []
    for spec in lines:
        product = _product(db_session, spec["price"], stock=10)
        params = {"product_id": product.id, "quantity": spec["quantity"]}
        unit_price = spec["price"]
        variant = None
        if spec["variant"] is not None:
            override = spec["variant"]["override"]
            variant = _variant(db_session, product, override, stock=10)
            params["variant_id"] = variant.id
            if override is not None:
                unit_price = override
        added = client.post(f"{CART}/items", params=params, headers=headers)
        assert added.status_code == 200, added.text
        expected_total += unit_price * spec["quantity"]
        expected_prices[(product.id, variant.id if variant else None)] = unit_price
        stocks.append((product, variant, spec["quantity"]))

    response = _checkout(client, headers, address_id)

    assert response.status_code == 200, response.text
    body = response.json()["data"]
    assert Decimal(body["total_amount"]) == expected_total
    db_session.expire_all()
    order = db_session.get(Order, body["id"])
    assert order.total_amount == expected_total
    items = db_session.query(OrderItem).filter(OrderItem.order_id == order.id).all()
    assert {(i.product_id, i.variant_id): i.price_at_time for i in items} == expected_prices
    assert sum(i.price_at_time * i.quantity for i in items) == order.total_amount
    # Only the counter the line was taken from moves.
    for product, variant, quantity in stocks:
        if variant is None:
            assert db_session.get(Product, product.id).stock_quantity == 10 - quantity
        else:
            assert db_session.get(Product, product.id).stock_quantity == 10
            assert db_session.get(ProductVariant, variant.id).stock_quantity == 10 - quantity

    # And the amount charged is that total, in cents.
    paid = client.post(
        f"{ORDERS}/{order.id}/pay",
        json={"order_id": order.id, "payment_method": "stripe",
              "amount": body["total_amount"], "payment_method_token": TOKEN_SUCCESS_DEFAULT},
        headers=headers,
    )
    assert paid.status_code == 200, paid.text
    db_session.expire_all()
    payment = order.payments[0]
    assert payment.amount == _decimal_to_cents(expected_total)


# -- Stock ---------------------------------------------------------------------

STOCK = 6

operation = st.one_of(
    # Add to the cart and check out at once: most sequences then have
    # orders to pay and cancel. "add" and "checkout" apart let a cart be
    # filled while stock lasts and checked out after the other buyer took
    # it, which is the case the checkout-time stock check is for.
    st.tuples(st.just("order"), st.integers(0, 1), st.integers(1, 4)),
    st.tuples(st.just("add"), st.integers(0, 1), st.integers(1, 4)),
    st.tuples(st.just("checkout"), st.integers(0, 1)),
    st.tuples(st.just("pay"), st.integers(0, 5)),
    st.tuples(st.just("cancel_by_customer"), st.integers(0, 5)),
    st.tuples(st.just("cancel_by_admin"), st.integers(0, 5)),
    st.tuples(st.just("expire")),
)


@hyp_settings(max_examples=50, **_HYPOTHESIS)
@given(operations=st.lists(operation, min_size=3, max_size=10))
def test_stock_equals_start_minus_live_orders_whatever_happens(
    client, db_session, tasks_db, operations
):
    product = _product(db_session, Decimal("5.00"), stock=STOCK)
    buyers = [_buyer(db_session), _buyer(db_session)]
    admin_headers, _ = _buyer(db_session, role="admin")
    for headers, _ in buyers:
        client.delete(CART, headers=headers)
    placed = []  # (order id, buyer index)

    def live_quantity():
        db_session.expire_all()
        return sum(
            item.quantity
            for order_id, _ in placed
            for item in db_session.get(Order, order_id).items
            if db_session.get(Order, order_id).status != "cancelled"
        )

    for op in operations:
        kind = op[0]
        if kind in ("add", "order"):
            headers, _ = buyers[op[1]]
            response = client.post(f"{CART}/items",
                                   params={"product_id": product.id, "quantity": op[2]},
                                   headers=headers)
            assert response.status_code in (200, 400), response.text
        if kind in ("checkout", "order"):
            headers, address_id = buyers[op[1]]
            response = _checkout(client, headers, address_id)
            # 400: empty cart, or not enough stock left for the cart.
            assert response.status_code in (200, 400), response.text
            if response.status_code == 200:
                placed.append((response.json()["data"]["id"], op[1]))
        if placed and kind in ("pay", "cancel_by_customer", "cancel_by_admin"):
            order_id, owner = placed[op[1] % len(placed)]
            headers, _ = buyers[owner]
            if kind == "pay":
                total = db_session.get(Order, order_id).total_amount
                response = client.post(
                    f"{ORDERS}/{order_id}/pay",
                    json={"order_id": order_id, "payment_method": "stripe",
                          "amount": str(total), "payment_method_token": TOKEN_SUCCESS_DEFAULT},
                    headers=headers,
                )
            elif kind == "cancel_by_customer":
                response = client.post(f"{ORDERS}/{order_id}/cancel", headers=headers)
            else:
                response = client.put(f"{ORDERS}/{order_id}/status",
                                      params={"status": "cancelled"}, headers=admin_headers)
            assert response.status_code in (200, 400), response.text
        if kind == "expire":
            for order_id, _ in placed:
                db_session.get(Order, order_id).created_at = datetime.utcnow() - timedelta(
                    minutes=settings.UNPAID_ORDER_EXPIRE_MINUTES + 1
                )
            db_session.commit()
            tasks.cancel_expired_unpaid_orders()

        db_session.expire_all()
        stock = db_session.get(Product, product.id).stock_quantity
        assert stock >= 0
        assert stock == STOCK - live_quantity(), (op, stock, placed)

    db_session.expire_all()
    cancelled = sum(db_session.get(Order, order_id).status == "cancelled" for order_id, _ in placed)
    event(f"orders placed: {len(placed)}, cancelled: {cancelled}")
